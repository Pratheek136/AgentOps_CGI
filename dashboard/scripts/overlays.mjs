// Screenshots of overlays/presenter mode while an incident is in progress. Usage: node scripts/overlays.mjs <outdir>
import { chromium } from "playwright";
const out = process.argv[2] ?? ".";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1366, height: 768 } });
await page.goto("http://localhost:5173");
await page.waitForSelector('[data-testid="conn"]');
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/o-idle-1366.png` });
await page.keyboard.press("h");
await page.waitForTimeout(400);
await page.screenshot({ path: `${out}/o-how.png` });
await page.keyboard.press("Escape");
await page.keyboard.press("?");
await page.waitForTimeout(300);
await page.screenshot({ path: `${out}/o-keys.png` });
await page.keyboard.press("Escape");
await fetch("http://127.0.0.1:8000/api/demo/fault/2", { method: "POST" });
await page.waitForSelector(".step-decision", { timeout: 120000 });
await page.click(".step-decision .chip >> nth=0");
await page.waitForSelector('[data-testid="evidence"] pre', { timeout: 10000 });
await page.waitForTimeout(500);
await page.screenshot({ path: `${out}/o-evidence.png` });
await page.keyboard.press("Escape");
await page.keyboard.press("p");
await page.waitForTimeout(500);
await page.screenshot({ path: `${out}/o-presenter.png` });
await browser.close();
console.log("overlays ok");
